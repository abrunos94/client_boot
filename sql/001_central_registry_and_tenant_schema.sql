-- ============================================================================
-- PARTE A: CADASTRO CENTRAL DE INTEGRAÇÕES (Control Plane do ClientFlow)
-- Roda exclusivamente no projeto central de roteamento do ClientFlow.
-- NUNCA armazena agendamentos, clientes ou finanças das empresas.
-- ============================================================================

CREATE TABLE IF NOT EXISTS central_integrations (
    integration_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL UNIQUE,
    waba_id VARCHAR(64) NOT NULL,
    phone_number_id VARCHAR(64) NOT NULL UNIQUE,
    secret_reference VARCHAR(255) NOT NULL,          -- Referência ao Token WABA da empresa no Vault
    supabase_url VARCHAR(255) NOT NULL,              -- URL do projeto Supabase exclusivo desta empresa
    supabase_secret_reference VARCHAR(255) NOT NULL, -- Referência à chave do Supabase exclusivo desta empresa
    status VARCHAR(32) NOT NULL CHECK (status IN ('active', 'pending', 'suspended', 'revoked')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS idx_central_integrations_phone_active
    ON central_integrations (phone_number_id)
    WHERE status = 'active' AND revoked_at IS NULL;

-- ============================================================================
-- PARTE B: SCHEMA EXISTENTE NO PROJETO SUPABASE INDIVIDUAL DE CADA CLIENTE
-- (7 Tabelas Operacionais da Empresa + Índices de Segurança/Concorrência do Bot)
-- ============================================================================

-- 1. Tabela: servicos
CREATE TABLE IF NOT EXISTS servicos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    nome TEXT NOT NULL,
    preco NUMERIC(10, 2) NOT NULL DEFAULT 0,
    ordem INTEGER NOT NULL DEFAULT 1
);

-- 2. Tabela: agendamentos
CREATE TABLE IF NOT EXISTS agendamentos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    cliente_nome TEXT NOT NULL,
    servico TEXT NOT NULL,
    telefone TEXT NOT NULL,
    data TEXT NOT NULL,     -- Formato YYYY-MM-DD
    horario TEXT NOT NULL,  -- Formato HH:mm
    status TEXT NOT NULL DEFAULT 'confirmado', -- 'confirmado' | 'cancelado' | 'bloqueado'
    valor NUMERIC(10, 2) NOT NULL DEFAULT 0
);

-- GARANTIA DE CONCORRÊNCIA (ZERO DOUBLE-BOOKING NO SUPABASE DA EMPRESA):
-- Impede fisicamente que duas requisições simultâneas (WhatsApp Bot e App/Site)
-- reservem a mesma data e horário enquanto o status não for 'cancelado' ou 'cancelled'.
CREATE UNIQUE INDEX IF NOT EXISTS uq_agendamentos_data_horario_ativo
    ON agendamentos (data, horario)
    WHERE status NOT IN ('cancelado', 'cancelled');

CREATE INDEX IF NOT EXISTS idx_agendamentos_data
    ON agendamentos (data);

CREATE INDEX IF NOT EXISTS idx_agendamentos_telefone
    ON agendamentos (telefone);

-- 3. Tabela: configuracoes
CREATE TABLE IF NOT EXISTS configuracoes (
    id INTEGER PRIMARY KEY,
    intervalo INTEGER NOT NULL DEFAULT 30,
    dias_trabalhados JSONB NOT NULL DEFAULT '["seg", "ter", "qua", "qui", "sex", "sab"]'::jsonb,
    meta_diaria NUMERIC(10, 2) NOT NULL DEFAULT 500.00,
    horarios_semana JSONB NOT NULL DEFAULT '["09:00", "10:00", "11:00", "14:00", "15:00", "16:00", "17:00"]'::jsonb,
    duracao_atendimento INTEGER NOT NULL DEFAULT 45
);

-- 4. Tabela: configuracoes1
CREATE TABLE IF NOT EXISTS configuracoes1 (
    id BIGINT PRIMARY KEY,
    hero_titulo TEXT,
    sobre_texto TEXT,
    endereco TEXT,
    mapa_iframe TEXT
);

-- 5. Tabela: templates_marketing
CREATE TABLE IF NOT EXISTS templates_marketing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    gatilho TEXT NOT NULL,
    texto_base TEXT NOT NULL
);

-- 6. Tabela: vitrine_midias
CREATE TABLE IF NOT EXISTS vitrine_midias (
    id BIGINT PRIMARY KEY,
    url_hero TEXT,
    url_sobre TEXT,
    tipo_exibicao TEXT,
    dados_galeria JSONB DEFAULT '[]'::jsonb,
    dados_produtos JSONB DEFAULT '[]'::jsonb,
    ultima_atualizacao TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Tabela: dados_barbearia (Dados da Empresa / Prestador)
CREATE TABLE IF NOT EXISTS dados_barbearia (
    id BIGINT PRIMARY KEY,
    proprietario TEXT NOT NULL,
    empresa TEXT NOT NULL,
    whatsapp TEXT NOT NULL,
    instagram TEXT,
    url_logo TEXT,
    chave_pix TEXT
);

-- 8. Tabela Auxiliar Não-Destrutiva do Bot: Controle de Idempotência de Webhooks Meta
CREATE TABLE IF NOT EXISTS processed_webhooks (
    message_id VARCHAR(128) PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '7 days')
);
